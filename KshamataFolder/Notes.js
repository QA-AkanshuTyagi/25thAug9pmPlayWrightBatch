// :-    " A Testing Technique is a method used to design test cases and execute tests to find defects in software.
 // It helps testers determine what should be tested and how it should be tested to ensure the software works correctly and meets requirements." 
  
 //       Type of Testing Techniques:
 //   1. Static Testing Techniques :-
 //  These are testing techniques that are performed without executing the code. Examples include code reviews, walkthroughs, and inspections.

 //   2. Dynamic Testing Techniques :- 
 // These are testing techniques that are performed by executing the code. Examples include unit testing, integration testing, and system testing.

 //   3. Black Box Testing Techniques :-
 //  These are testing techniques that test the functionality of the software without considering its internal structure or implementation details.

 //   4. White Box Testing Techniques :-
 //  These are testing techniques that test the internal structure or implementation details of the software.

 //   5. Grey Box Testing Techniques :- 
//  These are testing techniques that combine elements of both black box and white box testing.

 //   6. Regression Testing Techniques :-
 //  These are testing techniques used to ensure that changes made to the software do not introduce new defects or break existing functionality.

 //  7. Exploratory Testing Techniques :-
 //  These are testing techniques that involve exploring the software without following a predefined test plan.

 //  8. Performance Testing Techniques :- 
 // These are testing techniques used to evaluate the performance of the software under various conditions.

 //  9. Security Testing Techniques :-
 //  These are testing techniques used to identify vulnerabilities and weaknesses in the software's security measures.

 //  10. Usability Testing Techniques :- 
 // These are testing techniques used to evaluate how easy and effective the software is for users to use.

 //  11. Compatibility Testing Techniques :- 
 // These are testing techniques used to ensure that the software works correctly across different platforms, browsers, and devices.

 // 12. Acceptance Testing Techniques :-
 //  These are testing techniques used to determine whether the software meets the acceptance criteria and is ready for release to end-users.

 //  13. Smoke Testing Techniques :- 
 // These are testing techniques used to verify that the most critical functionalities of the software are working as expected.

 //  14. Sanity Testing Techniques :-
 //  These are testing techniques used to ensure that the software is functioning correctly after a change or fix.

 //  15. Ad-hoc Testing Techniques :- 
 // These are testing techniques that involve testing the software without following a predefined test plan.

 //  16. Boundary Value Testing Techniques :-
 //  These are testing techniques used to test the boundaries of input values.

 //  17. Equivalence Partitioning Testing Techniques :-
 //  These are testing techniques used to divide the input data into different partitions and test each partition.

 //  18. Decision Table Testing Techniques :- 
 // These are testing techniques used to test complex business logic with multiple conditions and actions.

 //  19. State Transition Testing Techniques :- 
 // These are testing techniques used to test the behavior of the software as it transitions from one state to another.

 //  20. Error Guessing Testing Techniques :-
 //  These are testing techniques used to identify potential errors based on the tester's experience and intuition.

 //  21. Load Testing Techniques :- These are testing techniques used to evaluate the performance of the software under expected load conditions.

 // 22. Stress Testing Techniques :- These are testing techniques used to evaluate the performance of the software under extreme load conditions.

 //  23. Volume Testing Techniques :- These are testing techniques used to evaluate the performance of the software under large volumes of data.

 //  24. Recovery Testing Techniques :- These are testing techniques used to evaluate the software's ability to recover from failures or crashes.

 // 25. Installation Testing Techniques :-
 //  These are testing techniques used to evaluate the installation process of the software and ensure that it is installed correctly and functions as expected.

 //  26. Alpha Testing Techniques :- These are testing techniques used to evaluate the software during the initial development phase.

 // 27. Beta Testing Techniques :- These are testing techniques used to evaluate the software by releasing it to a limited group of end-users before the final release.

 // 28. End-to-End Testing Techniques :- These are testing techniques used to evaluate the software's behavior from start to finish.

 // 29. Integration Testing Techniques :- These are testing techniques used to evaluate the interaction between different modules or components of the software.

 // 30. System Testing Techniques :- These are testing techniques used to evaluate the complete integrated software system.

// 31. Unit Testing Techniques :- These are testing techniques used to evaluate individual units or components of the software.