//Arithmatic operators:-

// +  Addition operator
// -, subtraction operator  
// *, multiplication operator
// /, division operator
// %, modulus operator
// ++, increment operator
// --, decrement operators

let a=23;
let b=22;
console.log("Addition of a and b is: ", a+b);
console.log("Subtraction of a and b is: ", a-b);
console.log("Multiplication of a and b is: ", a*b);
console.log("Division of a and b is: ", a/b);
console.log("Modulus of a and b is: ", a%b); 

// Assignment operators:-

// +=, addition assignment operator
// -=, subtraction assignment operator
// *=, multiplication assignment operator
// /=, division assignment operator
// %=, modulus assignment operator

console.log(a+=b);      // a = a + b here the value of a will be updated to 45 
console.log(a-=b);     // a = a - b  here the value of a will be updated to 23
console.log(a*=b);     //a = a * b  here the value of a will be updated to 506
console.log(a/=b);      // a = a / b here the value of a will be updated to 23
console.log(a%=b);      // a = a % b here the value of a will be updated to 1
// now the updated value of a is 1 and b is 22.


// Comparison operators:-

// ==, equal to operator
// ===, equal value and equal type operator
// !=, not equal operator
// !==, not equal value or not equal type operator
// >, greater than operator
// <, less than operator
// >=, greater than or equal to operator
// <=, less than or equal to operator

a=32;
console.log(a==b);      // false
console.log(a===b);    // false
console.log(a!=b);     // true
console.log(a!==b);    // true
console.log(a>b);   // true
console.log(a<b);   // false
console.log(a>=b);   // true
console.log(a<=b);   // false    
//now the updated value of a is 32 and b is 22.


